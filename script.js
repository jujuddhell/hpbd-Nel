const guestLayer = document.getElementById("guestLayer");
const modal = document.getElementById("greetingModal");
const modalTitle = document.getElementById("modalTitle");
const greetingText = document.getElementById("greetingText");
const greetingSignature = document.getElementById("greetingSignature");
const closeButton = document.getElementById("closeModal");
const houseIllustration = document.querySelector(".house-illustration");
const customHouseImage = document.getElementById("customHouseImage");
let lastFocusedElement = null;

greetings.forEach((greeting, index) => {
  const button = document.createElement("button");

  button.type = "button";
  button.className = "guest-name";
  button.textContent = greeting.name;

  button.style.setProperty("--x", `${greeting.x}%`);
  button.style.setProperty("--y", `${greeting.y}%`);
  button.style.setProperty("--tilt", `${greeting.tilt || 0}deg`);

  button.setAttribute(
    "aria-label",
    `Открыть поздравление от ${greeting.name}`
  );

  button.addEventListener("click", () => openGreeting(greeting, button));

  guestLayer.appendChild(button);
});

function openGreeting(greeting, trigger) {

    lastFocusedElement = trigger;

    // Заголовок поздравления
    modalTitle.textContent =
        `Поздравление от ${greeting.name}`;

    // Текст поздравления
    greetingText.textContent = greeting.text;

    // Подпись автора
    greetingSignature.textContent =
        greeting.signature || `С теплом, ${greeting.name}`;

    // Сначала возвращаем стандартный домик
    houseIllustration.classList.remove("has-custom-image");

    customHouseImage.onerror = null;
    customHouseImage.removeAttribute("src");

    // Если у автора есть собственный рисунок
    if (greeting.image) {

        customHouseImage.onerror = function () {

            // Если изображение не загрузилось,
            // оставляем стандартный домик
            houseIllustration.classList.remove(
                "has-custom-image"
            );

        };

        customHouseImage.onload = function () {

            houseIllustration.classList.add(
                "has-custom-image"
            );

        };

        customHouseImage.src = greeting.image;
    }

    // Открываем карточку
    modal.classList.add("is-open");
    modal.setAttribute("aria-hidden", "false");

    document.body.style.overflow = "hidden";

    closeButton.focus();
}

function closeGreeting() {
  modal.classList.remove("is-open");
  modal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
  if (lastFocusedElement) lastFocusedElement.focus();
}

closeButton.addEventListener("click", closeGreeting);
modal.addEventListener("click", (event) => {
  if (event.target === modal) closeGreeting();
});
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && modal.classList.contains("is-open")) closeGreeting();
});
